#!/usr/bin/env python3
"""Compare raw and post-trim FastQC exports made by 04_export_fastqc_metrics.py.

Standard-library only. This script reads metric TSVs; it does not access or alter FASTQ files.
"""
import argparse
import csv
import re
from collections import Counter
from pathlib import Path

MODULES = ["per_base_quality", "per_sequence_quality", "adapter_content", "per_base_n_content", "overrepresented_sequences"]


def sample_key(filename, trimmed=False):
    filename = Path(filename).name
    if trimmed:
        match = re.fullmatch(r"(.+)_R([12])_paired\.fastq(?:\.gz)?", filename)
    else:
        match = re.fullmatch(r"(.+)_reads_([12])\.fastq(?:\.gz)?", filename)
    if not match:
        raise ValueError(f"Unrecognized {'trimmed' if trimmed else 'raw'} FASTQ name: {filename}")
    return (match.group(1), match.group(2))


def load_rows(path, trimmed=False):
    with path.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))
    if not rows:
        raise ValueError(f"No rows in {path}")
    result = {}
    for row in rows:
        key = sample_key(row["filename"], trimmed=trimmed)
        if key in result:
            raise ValueError(f"Duplicate key {key} in {path}")
        result[key] = row
    return result


def merge(raw, trimmed):
    if set(raw) != set(trimmed):
        raise ValueError(f"Input groups differ: raw-only={sorted(set(raw)-set(trimmed))}, trimmed-only={sorted(set(trimmed)-set(raw))}")
    if len(raw) != 6:
        raise ValueError(f"Expected six paired-end FASTQ inputs; found {len(raw)}")
    out=[]
    for key in sorted(raw):
        r,t=raw[key], trimmed[key]
        rec={"group":key[0], "mate":key[1], "raw_sequences":r["total_sequences"],
             "trimmed_sequences":t["total_sequences"], "raw_gc_percent":r["gc_percent"],
             "trimmed_gc_percent":t["gc_percent"], "raw_length":r["sequence_length"],
             "trimmed_length":t["sequence_length"]}
        for m in MODULES:
            rec[f"raw_{m}"]=r.get(m,"missing")
            rec[f"trimmed_{m}"]=t.get(m,"missing")
        out.append(rec)
    return out


def count_flags(records, module, which):
    return Counter(rec[f"{which}_{module}"].lower() for rec in records)


def render(records):
    lines=["# Raw versus trimmed FastQC comparison (automatically generated)","",
           "**Data:** Exported from the raw and trimmed FastQC ZIP files; six read files in three NA12878 paired-end groups.",
           "**Interpretation:** FastQC pass/warn/fail calls are screening categories and do not by themselves establish biological validity.","",
           "| Module | Raw: pass / warn / fail | Trimmed: pass / warn / fail |", "|---|---|---|"]
    for m in MODULES:
        a=count_flags(records,m,"raw"); b=count_flags(records,m,"trimmed")
        fmt=lambda x:f"{x['pass']} / {x['warn']} / {x['fail']}" 
        lines.append(f"| {m.replace('_',' ')} | {fmt(a)} | {fmt(b)} |")
    lines.extend(["", "## Per-file comparison", "", "| Group | Mate | Raw reads | Trimmed reads | Raw GC % | Trimmed GC % | Raw length | Trimmed length | Raw adapter | Trimmed adapter | Raw base quality | Trimmed base quality |", "|---|---|---:|---:|---:|---:|---|---|---|---|---|---|"])
    for rec in records:
        lines.append("| "+" | ".join(str(rec[k]) for k in ("group","mate","raw_sequences","trimmed_sequences","raw_gc_percent","trimmed_gc_percent","raw_length","trimmed_length","raw_adapter_content","trimmed_adapter_content","raw_per_base_quality","trimmed_per_base_quality"))+" |")
    lines.extend(["", "**Caveat:** This table contains paired-read output only, not the unpaired Trimmomatic survivor counts. Consult `logs/trimmomatic_*.log` for the full trimming balance.", "", "Review post-trim Per Base Sequence Quality, N Content and Adapter Content plots before finalizing the scientific report.",""])
    return "\n".join(lines)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--raw',type=Path,default=Path('docs/qc_metrics.tsv'))
    p.add_argument('--trimmed',type=Path,default=Path('docs/qc_metrics_trimmed.tsv'))
    p.add_argument('--tsv',type=Path,default=Path('docs/qc_comparison.tsv'))
    p.add_argument('--report',type=Path,default=Path('docs/QC_COMPARISON_AUTOGENERATED.md'))
    args=p.parse_args()
    records=merge(load_rows(args.raw),load_rows(args.trimmed,trimmed=True))
    args.tsv.parent.mkdir(parents=True,exist_ok=True)
    with args.tsv.open('w',newline='',encoding='utf-8') as handle:
        w=csv.DictWriter(handle,fieldnames=list(records[0]),delimiter='\t')
        w.writeheader(); w.writerows(records)
    args.report.parent.mkdir(parents=True,exist_ok=True)
    args.report.write_text(render(records),encoding='utf-8')
    print(f'Compared {len(records)} raw/trimmed FASTQ files.')
    print(f'Wrote {args.tsv} and {args.report}.')

if __name__=='__main__':
    main()
