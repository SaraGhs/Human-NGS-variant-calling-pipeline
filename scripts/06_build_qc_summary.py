#!/usr/bin/env python3
"""Summarize exported FastQC metrics and verified FASTQ inventory; no fabricated results."""
from pathlib import Path
import argparse,csv,datetime

def load_tsv(path):
    with path.open(newline='',encoding='utf-8') as f: return list(csv.DictReader(f,delimiter='\t'))

def build(qc,pairs):
    if len(qc)!=6 or len(pairs)!=3:
        raise ValueError(f'Expected six FastQC and three pair records; got {len(qc)}, {len(pairs)}')
    lines=['# Automatically extracted raw-read QC metrics','',
           '**Source:** Six local FastQC ZIP archives and record-level validation of three paired-end FASTQ groups.','',
           '**Status:** Automated measurements only; requires human review of adapter graphs and technical interpretation.','',
           '| FASTQ file | Reads | Length (bp) | GC (%) | Per-base quality | Per-sequence quality | Adapter content | N content |',
           '|---|---:|---|---:|---|---|---|---|']
    for x in qc:
        lines.append('| '+ ' | '.join([x.get('filename',''),x.get('total_sequences',''),x.get('sequence_length',''),x.get('gc_percent',''),x.get('per_base_quality',''),x.get('per_sequence_quality',''),x.get('adapter_content',''),x.get('per_base_n_content','')])+' |')
    lines += ['', '## Verified paired-read structure','', '| Group | Pairs | Min length | Max length | Mean length |', '|---|---:|---:|---:|---:|']
    for x in pairs:
        lines.append(f"| {x['group']} | {x['read_pairs']} | {x['min_length_bp']} | {x['max_length_bp']} | {x['mean_length_bp']} |")
    lines += ['', '**Interpretation boundaries:** FastQC `fail`/`warn` flags are screening indicators, not proof that the whole library is unusable. Review adapter-content and overrepresented-sequence plots, and verify downstream trimming parameters. No read trimming, mapping or variant-call results are claimed here.', '',
              'For interpretation and screenshots, see `docs/QC_REPORT.md`. For data origin, see `docs/DATA_PROVENANCE.md`.', '']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--metrics',type=Path,default=Path('docs/qc_metrics.tsv'))
    p.add_argument('--inventory',type=Path,default=Path('docs/fastq_pair_inventory.tsv'))
    p.add_argument('--out',type=Path,default=Path('docs/QC_METRICS_AUTOGENERATED.md'))
    a=p.parse_args(); a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(build(load_tsv(a.metrics),load_tsv(a.inventory)),encoding='utf-8')
    print('Wrote',a.out)
if __name__=='__main__': main()
