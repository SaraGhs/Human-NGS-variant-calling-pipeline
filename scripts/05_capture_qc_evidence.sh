#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
[[ -d data/source/NA12878_20k ]] || { echo 'Missing FASTQ folder data/source/NA12878_20k' >&2; exit 1; }
[[ -d results/qc/raw ]] || { echo 'Missing original FastQC reports results/qc/raw' >&2; exit 1; }
mkdir -p docs logs
python scripts/05_validate_fastq_pairs.py \
  --fastq-dir data/source/NA12878_20k \
  --out docs/fastq_pair_inventory.tsv
python scripts/04_export_fastqc_metrics.py \
  --fastqc-dir results/qc/raw \
  --out docs/qc_metrics.tsv
python scripts/06_build_qc_summary.py \
  --metrics docs/qc_metrics.tsv \
  --inventory docs/fastq_pair_inventory.tsv \
  --out docs/QC_METRICS_AUTOGENERATED.md
sha256sum data/source/NA12878_20k/*.fastq > logs/raw_fastq_checksums.sha256
{
  printf 'Captured UTC: '; date -u +'%Y-%m-%dT%H:%M:%SZ'
  printf 'FastQC: '; fastqc --version 2>&1 || true
  printf 'MultiQC: '; multiqc --version 2>&1 || true
  printf 'Python: '; python --version 2>&1 || true
  printf 'GATK: '; gatk --version 2>&1 | head -2 || true
} > docs/QC_TOOL_VERSIONS.txt
printf '\nSUCCESS: raw FASTQ validation, FastQC metric export and documentation generated.\n'
printf 'Next: review docs/QC_METRICS_AUTOGENERATED.md and inspect adapter plots in MultiQC.\n'
