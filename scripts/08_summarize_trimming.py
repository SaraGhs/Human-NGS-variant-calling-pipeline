#!/usr/bin/env python3
"""Compare raw vs paired retained read counts (each group); results generated only after trimming."""
from pathlib import Path
import argparse,csv,gzip

def reads(path):
    op=gzip.open if str(path).endswith('.gz') else open
    n=0
    with op(path,'rt') as f:
        while f.readline():
            s=f.readline(); plus=f.readline(); q=f.readline()
            if not s or not plus or not q: raise ValueError(f'Truncated FASTQ: {path}')
            n+=1
    return n

def main():
    p=argparse.ArgumentParser(); p.add_argument('--root',type=Path,default=Path('.')); a=p.parse_args()
    src=a.root/'data/source/NA12878_20k'; trim=a.root/'results/trimmed'
    rows=[]
    for r1 in sorted(src.glob('*_reads_1.fastq')):
        stem=r1.name.replace('_reads_1.fastq','')
        raw=reads(r1)
        r1p=trim/f'{stem}_R1_paired.fastq.gz'; r2p=trim/f'{stem}_R2_paired.fastq.gz'
        if not r1p.is_file() or not r2p.is_file(): raise ValueError(f'Missing trimmed mates for {stem}')
        kept=reads(r1p)
        if kept!=reads(r2p): raise ValueError(f'Trimmed mate counts differ: {stem}')
        pct=100*kept/raw if raw else 0
        rows.append(dict(group=stem,raw_pairs=raw,retained_pairs=kept,retention_percent=f'{pct:.2f}',discarded_or_unpaired_pairs=raw-kept))
    if len(rows)!=3: raise ValueError(f'Expected 3 pairs, got {len(rows)}')
    out=a.root/'docs'; out.mkdir(exist_ok=True)
    with (out/'trimming_summary.tsv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]),delimiter='\t');w.writeheader();w.writerows(rows)
    lines=['# Trimming results — automatically generated','', '**Interpretation pending review of post-trim FastQC/MultiQC and logs.**','', '| Group | Raw read pairs | Retained read pairs | Retention (%) | Lost paired reads |', '|---|---:|---:|---:|---:|']
    for r in rows: lines.append(f"| {r['group']} | {r['raw_pairs']} | {r['retained_pairs']} | {r['retention_percent']} | {r['discarded_or_unpaired_pairs']} |")
    lines.extend(['', 'Paired-read retention counts were calculated from the two retained paired FASTQ files per group. **Lost paired reads** include reads that become unpaired or are discarded; this column does not quantify molecules removed specifically by any one filter.', '', 'See original logs in `logs/trimmomatic_*.log` and post-trimming report in `results/reports/multiqc_trimmed.html`.',''])
    (out/'TRIMMING_METRICS_AUTOGENERATED.md').write_text('\n'.join(lines))
    print('Created docs/trimming_summary.tsv and docs/TRIMMING_METRICS_AUTOGENERATED.md')
if __name__=='__main__':main()
